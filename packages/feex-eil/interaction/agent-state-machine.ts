/**
 * FEEX EIL — Agent State Machine  (Gate 2)
 *
 * Event-sourced state machine over the canonical AgentState contract.
 * Every transition emits a validated AgentStateEvent to subscribers.
 * The machine never invents states: it only applies transitions declared in
 * VALID_TRANSITIONS, and it throws on illegal transitions rather than
 * silently degrading.
 *
 * Rules enforced here (briefing §4 / acceptance §13):
 *   - Invalid transitions throw.
 *   - RESPONDING / EXECUTING require non-empty evidenceRefs.
 *   - confidence is omitted unless explicitly supplied — never defaulted.
 *   - EXECUTING reflects actual task execution events only.
 *   - Emitted events are frozen; history is a copy on read.
 *   - A throwing subscriber cannot starve later subscribers or leave a
 *     partially-delivered transition; errors surface after delivery.
 *   - Subscribers that transition re-entrantly are queued so every
 *     subscriber observes events in emission order.
 *   - Replayed logs must begin from a quiescent state and carry unique
 *     event IDs — a truncated or forged prefix is rejected.
 */

import {
  isValidAgentStateTransition,
  VALID_TRANSITIONS,
  transitionRequiresEvidence,
  type AgentState,
  type AgentStateEvent,
  type AgentStateMachine,
} from "../contracts/agent-state";
import { parseAgentStateEvent } from "../contracts/validation";

export type AgentStateSource = AgentStateEvent["source"];

export interface AgentStateMachineOptions {
  agentId: string;
  /** Initial state. Defaults to OFFLINE — agents boot unavailable, not IDLE. */
  initialState?: AgentState;
  /** Injectable ID factory for deterministic tests. */
  createEventId?: () => string;
  /** Injectable clock for deterministic tests. Must return ISO 8601 UTC. */
  now?: () => string;
}

/**
 * States a persisted log may legitimately claim as its starting point.
 * Transient states (LISTENING … EXECUTING) as an initial state indicate a
 * truncated or forged prefix — machines generated by this class always
 * begin OFFLINE and pass through IDLE before any transient state.
 */
const REPLAYABLE_INITIAL_STATES: readonly AgentState[] = [
  "IDLE",
  "OFFLINE",
  "ERROR",
];

function deepFreeze<T>(value: T): T {
  if (value !== null && typeof value === "object") {
    for (const key of Object.keys(value)) {
      deepFreeze((value as Record<string, unknown>)[key]);
    }
    Object.freeze(value);
  }
  return value;
}

export class AgentStateMachineImpl implements AgentStateMachine {
  private state: AgentState;
  private readonly agentId: string;
  private readonly createEventId: () => string;
  private readonly now: () => string;
  private readonly history: AgentStateEvent[] = [];
  private readonly handlers = new Set<(event: AgentStateEvent) => void>();
  private dispatching = false;
  private readonly queue: AgentStateEvent[] = [];

  constructor(options: AgentStateMachineOptions) {
    const initial = options.initialState ?? "OFFLINE";
    this.agentId = options.agentId;
    this.state = initial;
    this.createEventId = options.createEventId ?? (() => crypto.randomUUID());
    this.now = options.now ?? (() => new Date().toISOString());
  }

  /** Interface method — current state. */
  currentState(): AgentState {
    return this.state;
  }

  /** Property accessor for callers that prefer `.currentState`. */
  get stateValue(): AgentState {
    return this.state;
  }

  /** Read-only audit trail of emitted events (defensive copy). */
  get events(): readonly AgentStateEvent[] {
    return [...this.history];
  }

  /**
   * Attempt a transition. Throws on illegal transitions and on
   * evidence-required states entered without evidenceRefs.
   */
  transition(
    to: AgentState,
    source: AgentStateSource,
    meta: Partial<
      Pick<
        AgentStateEvent,
        "evidenceRefs" | "correlationId" | "confidence" | "debug" | "reason"
      >
    > = {},
  ): AgentStateEvent {
    const from = this.state;

    if (!isValidAgentStateTransition(from, to)) {
      throw new Error(
        `Invalid AgentState transition: ${from} → ${to}. Allowed: ${VALID_TRANSITIONS[from].join(", ")}`,
      );
    }

    const evidenceRefs = meta.evidenceRefs ?? [];
    if (transitionRequiresEvidence(to) && evidenceRefs.length === 0) {
      throw new Error(
        `AgentState ${to} requires non-empty evidenceRefs. ` +
          `Provide at least one evidence ID.`,
      );
    }

    const event: AgentStateEvent = {
      eventId: this.createEventId(),
      agentId: this.agentId,
      state: to,
      previousState: from,
      timestamp: this.nextTimestamp(),
      source,
      evidenceRefs,
      ...(meta.correlationId !== undefined && {
        correlationId: meta.correlationId,
      }),
      // CONSTRAINT: confidence omitted unless explicitly supplied.
      ...(meta.confidence !== undefined && { confidence: meta.confidence }),
      ...(meta.reason !== undefined && { reason: meta.reason }),
      ...(meta.debug !== undefined && { debug: meta.debug }),
    };

    // Boundary validation: the emitted event must satisfy the contract
    // schema before it reaches subscribers or history. The validated event
    // is frozen so neither subscribers nor callers can mutate the record.
    const validated = deepFreeze(parseAgentStateEvent(event));

    this.state = to;
    this.history.push(validated);
    this.dispatch(validated);
    return validated;
  }

  /**
   * Monotonic timestamp source: ISO timestamps have millisecond
   * precision, so synchronous transitions (e.g. IDLE → PERCEIVING →
   * THINKING inside one applySignals pass) can share a timestamp.
   * Consumers order events by timestamp, so each emitted event must be
   * strictly newer than the last — bump by 1ms when the clock does
   * not advance. Unparseable clock output passes through unchanged;
   * contract validation rejects it downstream (fail closed).
   */
  private nextTimestamp(): string {
    const ts = this.now();
    const last = this.history[this.history.length - 1]?.timestamp;
    if (!last) return ts;
    const tsMs = Date.parse(ts);
    const lastMs = Date.parse(last);
    if (Number.isNaN(tsMs) || Number.isNaN(lastMs) || tsMs > lastMs) return ts;
    return new Date(lastMs + 1).toISOString();
  }

  private dispatch(event: AgentStateEvent): void {
    if (this.dispatching) {
      this.queue.push(event);
      return;
    }
    this.dispatching = true;
    const errors: unknown[] = [];
    try {
      this.notify(event, errors);
      while (this.queue.length > 0) {
        this.notify(this.queue.shift()!, errors);
      }
    } finally {
      this.dispatching = false;
    }
    if (errors.length > 0) {
      const detail = errors
        .map((e) => (e instanceof Error ? e.message : String(e)))
        .join("; ");
      throw new Error(
        `[AgentStateMachine] ${errors.length} subscriber(s) threw during notification: ${detail}`,
      );
    }
  }

  private notify(event: AgentStateEvent, errors: unknown[]): void {
    // Snapshot: subscribers added/removed mid-notification apply to the
    // next event, keeping delivery order deterministic.
    for (const handler of [...this.handlers]) {
      try {
        handler(event);
      } catch (error) {
        errors.push(error);
      }
    }
  }

  /** Subscribe to transition events. Returns an unsubscribe function. */
  subscribe(handler: (event: AgentStateEvent) => void): () => void {
    this.handlers.add(handler);
    return () => {
      this.handlers.delete(handler);
    };
  }

  /** Rehydrate from a persisted event log. Rejects invalid sequences. */
  static fromEvents(
    agentId: string,
    events: readonly AgentStateEvent[],
    options?: Omit<AgentStateMachineOptions, "agentId" | "initialState">,
  ): AgentStateMachineImpl {
    if (events.length === 0) {
      return new AgentStateMachineImpl({ ...options, agentId });
    }

    const first = parseAgentStateEvent(events[0]);
    if (!REPLAYABLE_INITIAL_STATES.includes(first.previousState)) {
      throw new Error(
        `Event log for agent ${agentId} claims initial state ` +
          `${first.previousState} — replay requires a quiescent starting ` +
          `state (IDLE, OFFLINE or ERROR); transient initials indicate a ` +
          `truncated or forged prefix`,
      );
    }

    const seenEventIds = new Set<string>();
    const machine = new AgentStateMachineImpl({
      ...options,
      agentId,
      initialState: first.previousState,
    });
    for (const raw of events) {
      const event = parseAgentStateEvent(raw);
      if (event.agentId !== agentId) {
        throw new Error(
          `Event agentId ${event.agentId} does not match machine agentId ${agentId}`,
        );
      }
      if (seenEventIds.has(event.eventId)) {
        throw new Error(
          `Event log contains duplicate eventId ${event.eventId}`,
        );
      }
      seenEventIds.add(event.eventId);
      const applied = machine.transition(event.state, event.source, {
        evidenceRefs: event.evidenceRefs,
        correlationId: event.correlationId,
        confidence: event.confidence,
        reason: event.reason,
        debug: event.debug,
      });
      if (
        applied.previousState !== event.previousState ||
        applied.state !== event.state
      ) {
        throw new Error(
          `Event log sequence invalid at ${event.eventId}: ` +
            `${event.previousState} → ${event.state} not reachable`,
        );
      }
      // Preserve original event identity/timestamp in history.
      machine.history[machine.history.length - 1] = deepFreeze(event);
    }
    return machine;
  }
}

export { AgentStateMachineImpl as AgentStateMachine };
